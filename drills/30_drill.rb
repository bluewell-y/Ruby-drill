num = rand(10)

if num >= 5
  puts "#{num}は4より大きい！"
else
  puts "#{num}は5より小さい！"
end

## 解説
## 何をするコードですか？
# 0から9までのランダムな数値を生成し、その数値が5以上かどうかを判定して、結果を表示するコードです。

## コードの意味
# num = rand(10)は、0から9までのランダムな数値を生成し、それをnumという変数に代入するという意味。
# if num >= 5は、numが5以上かどうかを判定する条件式。
# puts "#{num}は4より大きい！"は、numが5以上の場合に実行される処理で、numの値を表示するという意味。
# elseは、ifの条件が満たされなかった場合に実行される処理を指定する。
# puts "#{num}は5より小さい！"は、numが5未満の場合に実行される処理で、numの値を表示するという意味。
