def lone_sum(ary)
  puts ary.select { |num| ary.count(num) == 1 }.sum
end

## 解説
## これは何をするコードか？
# 配列の中で一度しか出現しない要素の合計を計算するメソッドlone_sumを定義し、
# 引数として渡された配列の中で一度しか出現しない要素の合計を計算して表示するプログラム

## selectメソッド
# selectメソッドは、配列の中から条件に合致する要素を選択して
# 新しい配列を作成するためのメソッドです。
# 例えば、配列[1, 2, 3, 2]に対してselect { |num| num > 2 }を呼び出すと、
# 配列の中から2より大きい要素である3が選択され、新しい配列[3]が作成されます。

## このコードの意味
# lone_sumメソッドを定義する。
# 引数として渡された配列の中で一度しか出現しない要素を選択するために、selectメソッドを使用する。
# selectメソッドのブロック内で、配列の中で要素が一度しか出現しないかどうかを判定するために、countメソッドを使用する。
# 配列の中で一度しか出現しない要素を選択した新しい配列を作成し、その合計を計算するために、sumメソッドを使用する。
# 配列の中で一度しか出現しない要素の合計を表示するために、putsで文字列を表示する。
# 呼び出し例として、lone_sumメソッドを呼び出し、配列の中で一度しか出現しない要素の合計を表示する。