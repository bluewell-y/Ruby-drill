def near_ten(num)
  total = (num/100) + (num/10 % 10) + (num % 10)
  remainder = total % 10
  if remainder <= 2 || remainder >= 8
    puts "True"
  elsif remainder <= 5
    puts "10の倍数との差は#{remainder}です"
  else 
    puts "10の倍数との差は#{10 - remainder}です"
  end
end

# 呼び出し例
near_ten(117)  # => True
near_ten(123)  # => 10の倍数との差は4です
near_ten(111)  # => 10の倍数との差は3です

## 解説
## これは何をするコードか？
# 引数として渡された整数の各桁の合計が10の倍数に近いかどうかを判定するメソッドnear_tenを定義し、
# 10の倍数に近い場合はTrue、そうでない場合は10の倍数との差を表示するプログラム

## コードの意味
# near_tenメソッドを定義する。
# 引数として渡された整数の各桁の合計を計算するために、
# 整数を100で割った商、10で割った商の余り、1の位の数を足し合わせる。
# 各桁の合計を10で割った余りを計算し、
# 余りが2以下または8以上の場合は10の倍数に近いと判断し、Trueを表示する。
# 余りが3から5の場合は10の倍数との差を表示し、
# 余りが6から7の場合は10の倍数との差を表示する。
# 呼び出し例として、near_tenメソッドを呼び出し、
# 引数として渡された整数の各桁の合計が10の倍数に近いかどうかを判定し結果を表示する。