def left2(str)
  puts str[2..-1] + str[0..1]  
end

## 解説
## これは何をするコードか？
# 文字列の先頭2文字を末尾に移動させるメソッドleft2を定義し、引数として渡された文字列の先頭2文字を末尾に移動させた新しい文字列を表示するプログラム

## コードの意味
# left2メソッドを定義する。
# 引数として渡された文字列の先頭2文字を末尾に移動させた新しい文字列を作成するために、文字列のスライスを使用する。
# str[2..-1]で文字列の3文字目以降を取得し、str[0..1]で文字列の先頭2文字を取得する。
# 取得した文字列を結合して新しい文字列を作成し、putsで表示する。


