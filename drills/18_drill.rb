def array_count9(nums)
  count = nums.count(9)
  puts "配列の中には9が#{count}個です"
end

# 呼び出し例
array_count9([1, 2, 9])          # => 配列の中には9が1個です
array_count9([1, 9, 9])          # => 配列の中には9が2個です
array_count9([1, 9, 9, 3, 9])    # => 配列の中には9が3個です

## 解説
## これは何をするコードか？
# 配列の中に含まれる9の個数を数えるメソッドarray_count9を定義し、
# 引数として渡された配列の中に含まれる9の個数を数えて表示するプログラム

## countメソッド
# countメソッドは、配列の中に含まれる指定された要素の個数を数えるためのメソッドです。
# 例えば、配列[1, 2, 9]に対してcount(9)を呼び出すと、
# 配列の中に含まれる9の個数が1であることが返されます。

## コードの意味
# array_count9メソッドを定義する。
# 引数として渡された配列の中に含まれる9の個数を数えるために、countメソッドを使用する。
# 配列の中に含まれる9の個数をcount変数に代入する。
# 配列の中に含まれる9の個数を表示するために、putsで文字列を表示する。
# 呼び出し例として、array_count9メソッドを呼び出し、配列の中に含まれる9の個数を表示する。