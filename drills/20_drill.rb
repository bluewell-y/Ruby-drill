def withdraw(balance, amount)
  fee = 110
  if balance >= (amount + fee)
    balance -= (amount + fee)
    puts "#{amount}円引き落としました。残高は#{balance}円です"
  else
    puts "残高不足です"
  end
end

## 解説
## これは何をするコードか？
# 引数として渡された残高と引き落とし金額をもとに、
# 引き落とし手数料を考慮して残高を更新するwithdrawメソッドを定義し、
# 残高が引き落とし金額と手数料を合わせた金額以上であれば引き落としを行い、
# 残高を表示するプログラム。
# 残高が不足している場合は「残高不足です」と表示する。

## withdrawメソッドとは
# withdrawメソッドは、口座や財布などの残高から指定された金額を引き落とすためのメソッドです。

