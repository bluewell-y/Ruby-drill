def array123(nums)
  if nums.include?(1) && nums.include?(2) && nums.include?(3)
    puts "True"
  else
    puts "False"
  end
end

# 呼び出し例
array123([1, 1, 2, 3, 1])       # => True
array123([1, 2, 4])             # => False
array123([1, 1, 2, 1, 4, 3])    # => True

## 解説

## これは何をするコードか？
# 配列（いろんな数字が入った箱）の中に、
# 1と2と3がそれぞれ1回でも入っているかをチェックするプログラム。

## include?メソッドとは
# 配列の中に指定した要素が含まれているかどうかをチェックするメソッド。

## コードの意味
# もし「1がある」そして「2がある」そして「3がある」の全部が当てはまったら「True」と言う。
# そうじゃなかったら、「False」と言う。

# &&は「そして」という意味。3つとも「はい」じゃないと、全体も「はい」にならないという約束。